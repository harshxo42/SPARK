"""
reports.py — SPARK PDF Report Generator
========================================
Generates professional inspection report PDFs using ReportLab.

DISCLAIMER: Reports generated by this module are DEMONSTRATION DOCUMENTS
produced by a software prototype. They are NOT certified inspection reports,
official maintenance records, or safety-critical documents. All findings
must be reviewed by a qualified maintenance engineer before any action is taken.
"""

from __future__ import annotations

import io
import os
from datetime import datetime
from pathlib import Path
from typing import Optional

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import cm, mm
from reportlab.platypus import (
    BaseDocTemplate,
    Frame,
    Image as RLImage,
    PageTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
    HRFlowable,
)

# ── Colour palette ────────────────────────────────────────────────────────────
NAVY = colors.HexColor("#0d1c2e")
CHARCOAL = colors.HexColor("#1e2d3d")
CYAN = colors.HexColor("#00c8c8")
STEEL = colors.HexColor("#4a90b8")
WHITE = colors.white
LIGHT_GRAY = colors.HexColor("#c8d8e8")
WARN_RED = colors.HexColor("#dc1e1e")
SOFT_GRAY = colors.HexColor("#8899aa")

PAGE_W, PAGE_H = A4


def _styles() -> dict:
    base = getSampleStyleSheet()
    styles = {}

    styles["title"] = ParagraphStyle(
        "SPARKTitle",
        fontSize=22,
        textColor=WHITE,
        fontName="Helvetica-Bold",
        spaceAfter=4,
        leading=26,
    )
    styles["subtitle"] = ParagraphStyle(
        "SPARKSubtitle",
        fontSize=11,
        textColor=CYAN,
        fontName="Helvetica",
        spaceAfter=2,
    )
    styles["demo_badge"] = ParagraphStyle(
        "DemoBadge",
        fontSize=9,
        textColor=WARN_RED,
        fontName="Helvetica-Bold",
        spaceAfter=0,
    )
    styles["section_head"] = ParagraphStyle(
        "SectionHead",
        fontSize=12,
        textColor=CYAN,
        fontName="Helvetica-Bold",
        spaceBefore=12,
        spaceAfter=4,
    )
    styles["body"] = ParagraphStyle(
        "SPARKBody",
        fontSize=9,
        textColor=LIGHT_GRAY,
        fontName="Helvetica",
        leading=14,
        spaceAfter=4,
    )
    styles["disclaimer"] = ParagraphStyle(
        "Disclaimer",
        fontSize=8,
        textColor=WARN_RED,
        fontName="Helvetica-Oblique",
        leading=12,
    )
    styles["footer"] = ParagraphStyle(
        "Footer",
        fontSize=7,
        textColor=SOFT_GRAY,
        fontName="Helvetica",
        alignment=1,
    )
    return styles


def _on_page(canvas, doc):
    """Draw page background and footer on every page."""
    canvas.saveState()
    # Background
    canvas.setFillColor(NAVY)
    canvas.rect(0, 0, PAGE_W, PAGE_H, fill=1, stroke=0)

    # Header bar
    canvas.setFillColor(CHARCOAL)
    canvas.rect(0, PAGE_H - 55, PAGE_W, 55, fill=1, stroke=0)
    canvas.setStrokeColor(CYAN)
    canvas.setLineWidth(2)
    canvas.line(0, PAGE_H - 55, PAGE_W, PAGE_H - 55)

    # SPARK header text
    canvas.setFillColor(CYAN)
    canvas.setFont("Helvetica-Bold", 16)
    canvas.drawString(25, PAGE_H - 35, "SPARK")
    canvas.setFillColor(LIGHT_GRAY)
    canvas.setFont("Helvetica", 9)
    canvas.drawString(25, PAGE_H - 48, "Spatial AI Repair Knowledge Platform  |  Inspection Report")

    # Page number
    canvas.setFillColor(SOFT_GRAY)
    canvas.setFont("Helvetica", 8)
    canvas.drawRightString(PAGE_W - 25, PAGE_H - 48, f"Page {doc.page}")

    # Demo watermark
    canvas.setFillColor(colors.HexColor("#dc1e1e"))
    canvas.setFont("Helvetica-Bold", 8)
    canvas.drawRightString(PAGE_W - 25, PAGE_H - 35, "DEMONSTRATION DOCUMENT")

    # Footer bar
    canvas.setFillColor(CHARCOAL)
    canvas.rect(0, 0, PAGE_W, 28, fill=1, stroke=0)
    canvas.setStrokeColor(STEEL)
    canvas.setLineWidth(0.5)
    canvas.line(0, 28, PAGE_W, 28)
    canvas.setFillColor(SOFT_GRAY)
    canvas.setFont("Helvetica", 7)
    canvas.drawString(
        25, 10,
        "Generated by SPARK prototype  |  NOT a certified inspection report  |  "
        "All findings must be reviewed by a qualified maintenance engineer.",
    )

    canvas.restoreState()


def _rl_image(path: str, max_w: float, max_h: float) -> Optional[RLImage]:
    """Load an image for ReportLab, respecting max dimensions. Returns None if unavailable."""
    if not path:
        return None
    p = Path(path)
    if not p.exists():
        return None
    try:
        img = RLImage(str(p))
        img_w, img_h = img.imageWidth, img.imageHeight
        scale = min(max_w / img_w, max_h / img_h, 1.0)
        img.drawWidth = img_w * scale
        img.drawHeight = img_h * scale
        return img
    except Exception:
        return None


def _kv_table(pairs: list[tuple[str, str]], styles_dict: dict) -> Table:
    """Build a two-column key-value table with dark styling."""
    data = [[Paragraph(k, styles_dict["subtitle"]), Paragraph(v, styles_dict["body"])]
            for k, v in pairs]
    t = Table(data, colWidths=[4.5 * cm, 11.5 * cm])
    t.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (0, -1), CHARCOAL),
                ("BACKGROUND", (1, 0), (1, -1), colors.HexColor("#0f1e30")),
                ("TEXTCOLOR", (0, 0), (-1, -1), LIGHT_GRAY),
                ("GRID", (0, 0), (-1, -1), 0.5, STEEL),
                ("LEFTPADDING", (0, 0), (-1, -1), 8),
                ("RIGHTPADDING", (0, 0), (-1, -1), 8),
                ("TOPPADDING", (0, 0), (-1, -1), 5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ]
        )
    )
    return t


def _section(title: str, styles_dict: dict) -> list:
    """Return flowables for a section header."""
    return [
        Spacer(1, 6),
        HRFlowable(width="100%", thickness=0.5, color=STEEL),
        Paragraph(title, styles_dict["section_head"]),
    ]


def generate_report(
    record: dict,
    images: dict,
    output_path: str,
) -> str:
    """
    Generate a PDF inspection report for the given record.

    Parameters
    ----------
    record  : dict — repair record fields (from database.get_record_by_id)
    images  : dict — image paths (from database.get_images_for_record)
    output_path : str — destination .pdf file path

    Returns
    -------
    str — absolute path of the generated PDF.
    """
    output_path = str(output_path)
    Path(output_path).parent.mkdir(parents=True, exist_ok=True)

    st = _styles()

    # Content margin area (below header bar, above footer)
    MARGIN_L = 25
    MARGIN_R = 25
    MARGIN_T = 65   # space for header
    MARGIN_B = 35   # space for footer

    doc = BaseDocTemplate(
        output_path,
        pagesize=A4,
        leftMargin=MARGIN_L,
        rightMargin=MARGIN_R,
        topMargin=MARGIN_T,
        bottomMargin=MARGIN_B,
    )
    frame = Frame(
        MARGIN_L, MARGIN_B,
        PAGE_W - MARGIN_L - MARGIN_R,
        PAGE_H - MARGIN_T - MARGIN_B,
        id="main",
    )
    doc.addPageTemplates([PageTemplate(id="main", frames=[frame], onPage=_on_page)])

    story = []

    # ── Report title ─────────────────────────────────────────────────────
    story.append(Spacer(1, 6))
    story.append(Paragraph("Gearbox Inspection Report", st["title"]))
    story.append(Paragraph("SPARK — Spatial AI Repair Knowledge Platform", st["subtitle"]))
    story.append(Paragraph("⚠ DEMONSTRATION DOCUMENT — Not a certified inspection report", st["demo_badge"]))
    story.append(Spacer(1, 8))

    # ── Record details table ─────────────────────────────────────────────
    story += _section("Record Details", st)
    story.append(
        _kv_table(
            [
                ("Record ID", str(record.get("record_id", "—"))),
                ("Gearbox Case", record.get("gearbox_case", "—")),
                ("Technician", record.get("technician_name", "—")),
                ("Inspection Date", record.get("inspection_date", "—")),
                ("Status", record.get("status", "—")),
                ("Created At", record.get("created_at", "—")),
            ],
            st,
        )
    )

    # ── Visual comparison results ─────────────────────────────────────────
    story += _section("Visual Comparison Results", st)
    cp = record.get("change_percent", 0.0)
    story.append(
        _kv_table(
            [
                (
                    "Visual Change %",
                    f"{cp:.2f}%  —  This is a pixel-comparison metric, NOT a fault probability.",
                ),
                (
                    "Comparison Summary",
                    record.get("comparison_summary", "No comparison performed."),
                ),
            ],
            st,
        )
    )

    # ── Images ───────────────────────────────────────────────────────────
    story += _section("Inspection Images", st)

    img_rows = []
    labels = [
        ("reference_path", "Reference Image (Baseline)"),
        ("current_path", "Current Inspection Image"),
        ("highlighted_path", "Highlighted Differences (Red = changed pixels)"),
    ]
    avail_w = PAGE_W - MARGIN_L - MARGIN_R  # ~160 mm
    img_cell_w = (avail_w - 12) / 3   # three columns

    cells = []
    for key, label in labels:
        rl_img = _rl_image(images.get(key, ""), img_cell_w, 100)
        if rl_img:
            cells.append([rl_img, Paragraph(label, st["footer"])])
        else:
            cells.append([
                Paragraph("[Image not available]", st["footer"]),
                Paragraph(label, st["footer"]),
            ])

    # Lay images in a single row
    img_table_data = [[c[0] for c in cells], [c[1] for c in cells]]
    img_t = Table(
        img_table_data,
        colWidths=[img_cell_w] * 3,
        rowHeights=[None, 14],
    )
    img_t.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#0f1e30")),
                ("GRID", (0, 0), (-1, -1), 0.5, STEEL),
                ("ALIGN", (0, 0), (-1, -1), "CENTER"),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("LEFTPADDING", (0, 0), (-1, -1), 4),
                ("RIGHTPADDING", (0, 0), (-1, -1), 4),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ]
        )
    )
    story.append(img_t)
    story.append(
        Paragraph(
            "Red-highlighted pixels indicate visual differences between reference and current images. "
            "This does NOT identify the cause or severity of any mechanical issue.",
            st["body"],
        )
    )

    # ── Technician observations ───────────────────────────────────────────
    story += _section("Technician Observations", st)
    story.append(
        Paragraph(
            record.get("observations", "No observations recorded.") or "No observations recorded.",
            st["body"],
        )
    )

    # ── Repair actions ────────────────────────────────────────────────────
    story += _section("Repair Action Notes", st)
    story.append(
        Paragraph(
            record.get("repair_actions", "No actions recorded.") or "No actions recorded.",
            st["body"],
        )
    )

    # ── Limitations and safety disclaimer ────────────────────────────────
    story += _section("Important Limitations & Safety Disclaimer", st)
    disclaimer_text = (
        "This report was generated by the SPARK software prototype, a final-year B.Tech demonstration project. "
        "It is NOT a certified industrial inspection report and must NOT be used as the basis for any maintenance "
        "decision, equipment operation, or safety assessment. "
        "<br/><br/>"
        "The visual comparison percentage shown in this report is a pixel-level metric derived from basic image "
        "differencing. It does NOT represent a probability of mechanical fault, structural damage, or equipment failure. "
        "<br/><br/>"
        "All inspection findings must be evaluated by a qualified maintenance engineer following applicable "
        "safety procedures, including lockout/tagout (LOTO) protocols. "
        "<br/><br/>"
        "Do not operate or approve repair of equipment based solely on this report."
    )
    story.append(Paragraph(disclaimer_text, st["disclaimer"]))

    # ── Generation timestamp ──────────────────────────────────────────────
    story.append(Spacer(1, 12))
    story.append(
        Paragraph(
            f"Report generated: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}  |  SPARK Prototype",
            st["footer"],
        )
    )

    doc.build(story)
    return output_path
